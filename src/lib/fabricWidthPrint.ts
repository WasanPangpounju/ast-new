// หน้ากว้างผ้า + เครื่องหมายนิ้ว สำหรับเอกสารที่พิมพ์/ส่งออก — แก้ที่นี่ที่เดียว
// fabricW บางค่ามีรหัสต่อท้าย "<หน้ากว้าง>/<รหัส>" เครื่องหมายนิ้วต้องอยู่หลังตัวเลข ไม่ใช่ท้ายสตริง
//   "63"        → 63''
//   "63/K3-K5"  → 63'' /K3-K5
//   "63.6\"/K-K" → 63.6'' /K-K   (ตัดเครื่องหมายนิ้วที่กรอกมาเองออกก่อน ไม่ให้ซ้อน)
//   "/71-79 67" → /71-79 67     (ไม่มีตัวเลขนำหน้า คืนค่าเดิม ไม่ใส่เครื่องหมาย)
export function formatFabricWidth(
  raw: string | null | undefined,
  mark = "''",
): string {
  const s = (raw ?? "").trim();
  if (!s) return "";
  const m = /^(\d+(?:\.\d+)?)\s*(?:''|"|”|″)?\s*(.*)$/u.exec(s);
  if (!m) return s;
  return m[2] ? `${m[1]}${mark} ${m[2]}` : `${m[1]}${mark}`;
}
